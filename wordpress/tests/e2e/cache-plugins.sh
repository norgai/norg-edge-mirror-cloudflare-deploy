#!/usr/bin/env bash
# Cache-plugin proofs against the real plugins (wordpress.org builds), on the e2e site.
#
# Usage: cache-plugins.sh <work-dir>   (after setup.sh; needs the zips in $E2E_CACHE)
#
# WP Super Cache serves cached pages from PHP, so its proof is end to end: a
# cached human page reaches GPTBot BEFORE the bypass, the NORG mirror AFTER.
# WP Fastest Cache and LiteSpeed serve hits from Apache/LiteSpeed rewrite rules,
# which PHP's built-in server cannot run, so those proofs check exactly what
# each plugin stores and generates. Every proof also checks deactivation cleanup.
set -uo pipefail
WORK="$1"; HERE="$(cd "$(dirname "$0")" && pwd)"; WP_DIR="$WORK/site"; CACHE="${E2E_CACHE:-$WORK/dl}"
PORT="${WP_PORT:-8889}"; MOCK_PORT="${MOCK_PORT:-8890}"; BASE="http://127.0.0.1:$PORT"
export MOCK_SITE_ID="${MOCK_SITE_ID:-9f1c2e4a-1111-4222-8333-444455556666}" MOCK_SITE_KEY="${MOCK_SITE_KEY:-nek_live_e2eTestKeyAAAAAAAAAAAAAAAAAAAAAA}"
export MOCK_LOG="$WORK/mock.jsonl" MOCK_STATE="$WORK/state"
PHP_BIN="${PHP_BIN:-$(command -v php)}"
GPT="Mozilla/5.0 (compatible; GPTBot/1.2; +https://openai.com/gptbot)"; BROWSER="Mozilla/5.0 (Macintosh) Chrome/125.0 Safari/537.36"
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '  \033[32m✓\033[0m %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  \033[31m✗ %s\033[0m  %s\n' "$1" "${2:-}"; }
check() { if eval "$2"; then ok "$1"; else bad "$1" "$2"; fi; }
wpcli() { (cd "$WP_DIR" && wp "$@" 2>/dev/null); }
edge_of() { curl -s -D "$WORK/ch" -o "$WORK/cb" -A "$1" "$BASE$2"; grep -i '^x-norg-edge:' "$WORK/ch" | tr -d '\r' | cut -d' ' -f2; }
cached() { grep -c 'Cached page generated by WP-Super-Cache' "$WORK/cb"; }
mkdir -p "$MOCK_STATE"; rm -f "$MOCK_STATE/refuse"
MOCK_FEED_TTL=3600 nohup "$PHP_BIN" -d opcache.enable_cli=0 -S "127.0.0.1:$MOCK_PORT" "$HERE/mock-norg.php" >"$WORK/mock.out" 2>&1 & MP=$!
PHP_CLI_SERVER_WORKERS=4 nohup "$PHP_BIN" -d opcache.enable_cli=0 -S "127.0.0.1:$PORT" -t "$WP_DIR" "$HERE/wp-router.php" >"$WORK/wp.out" 2>&1 & WP=$!
trap 'kill $MP 2>/dev/null; pkill -P $WP 2>/dev/null; kill $WP 2>/dev/null' EXIT; sleep 1
for out in "$WORK/wp.out" "$WORK/mock.out"; do grep -q "Failed to listen" "$out" && { echo "port in use: $(cat "$out")" >&2; exit 2; }; done
for p in wp-super-cache wp-fastest-cache litespeed-cache; do [ -d "$WP_DIR/wp-content/plugins/$p" ] || unzip -q -o "$CACHE/$p.zip" -d "$WP_DIR/wp-content/plugins/"; done
printf '# BEGIN WordPress\n<IfModule mod_rewrite.c>\nRewriteEngine On\n</IfModule>\n# END WordPress\n' > "$WP_DIR/.htaccess"
wpcli plugin deactivate wp-fastest-cache litespeed-cache --quiet; wpcli option delete norg_edge_bypass
wpcli option delete WpFastestCacheExclude
set_bypass() { wpcli eval "\$o = (array) get_option( 'norg_edge_settings', array() ); \$o['cache_bypass'] = $1; update_option( 'norg_edge_settings', \$o );"; }
# The plugin re-applies the bypass by itself (via WP-Cron) whenever the feed's agent list changes,
# so it is switched off to reproduce the BEFORE state deliberately.
set_bypass false

echo "WP Super Cache (served from PHP: full before/after proof)"
wpcli plugin deactivate wp-super-cache --quiet; wpcli plugin activate wp-super-cache --quiet; wpcli eval "wp_cache_enable();"
rm -f "$WP_DIR/wp-content/plugins/wp-super-cache-plugins/norg-edge-router.php"
sed -i "s/^\$cache_rejected_user_agent = .*/\$cache_rejected_user_agent = array();/" "$WP_DIR/wp-content/wp-cache-config.php"
rm -rf "$WP_DIR/wp-content/cache/supercache"
# Warm until WP Super Cache is genuinely serving from cache (its config file was just rewritten).
for i in 1 2 3 4 5 6 7 8; do edge_of "$BROWSER" / >/dev/null; [ "$(cached)" = 1 ] && break; sleep 1; done
check "people get the cached page" '[ "$(cached)" = 1 ]'
E="$(edge_of "$GPT" /)"; C="$(cached)"
check "BEFORE: GPTBot is served the cached human page (the failure mode)" '[ -z "$E" ] && [ "$C" = 1 ]'
check "BEFORE: the self-check reports cache interference" '[[ "$(wpcli norg-edge check)" == *"\"cache_reach\": \"cache_interference\""* ]]'
set_bypass true; wpcli norg-edge apply-cache-bypass >/dev/null
check "the phase-1 extension is written" '[ -f "$WP_DIR/wp-content/plugins/wp-super-cache-plugins/norg-edge-router.php" ]'
check "the tokens are in \$cache_rejected_user_agent" 'grep -q "gptbot" "$WP_DIR/wp-content/wp-cache-config.php"'
E="$(edge_of "$GPT" /)"
check "AFTER: GPTBot gets the NORG mirror" '[ "$E" = mirror ]'
edge_of "$BROWSER" / >/dev/null
check "AFTER: people still get the cached page" '[ "$(cached)" = 1 ]'
check "AFTER: the self-check reports reached" '[[ "$(wpcli norg-edge check)" == *"\"cache_reach\": \"reached\""* ]]'
check "no NORG content ever lands in the cache" '! grep -rq "NORG-RENDER" "$WP_DIR/wp-content/cache/"'
wpcli plugin deactivate norg-edge-router --quiet
check "deactivation removes the extension" '[ ! -f "$WP_DIR/wp-content/plugins/wp-super-cache-plugins/norg-edge-router.php" ]'
check "deactivation removes the tokens" '! grep -q "gptbot" "$WP_DIR/wp-content/wp-cache-config.php"'
wpcli plugin activate norg-edge-router --quiet
# The live server may already have spawned a WP-Cron run that consumed the event, so
# "scheduled" or "already applied" both pass; the next check proves the outcome.
check "reactivation schedules the bypass re-apply on WP-Cron" '[[ "$(wpcli cron event list --fields=hook --format=csv)" == *norg_edge_apply_cache_bypass* ]] || [ -f "$WP_DIR/wp-content/plugins/wp-super-cache-plugins/norg-edge-router.php" ]'
wpcli cron event run --due-now --quiet
check "the scheduled re-apply restores the bypass with no manual command" '[ -f "$WP_DIR/wp-content/plugins/wp-super-cache-plugins/norg-edge-router.php" ]'
wpcli plugin deactivate wp-super-cache --quiet

echo "WP Fastest Cache (served by rewrite rules: configuration proof)"
wpcli plugin activate wp-fastest-cache --quiet; wpcli option update WpFastestCache '{"wpFastestCacheStatus":"on"}' --quiet
wpcli norg-edge apply-cache-bypass >/dev/null
check "user-agent exclude rules stored in WPFC's own shape" '[[ "$(wpcli option get WpFastestCacheExclude)" == *"\"content\":\"gptbot\",\"type\":\"useragent\""* ]]'
check "WPFC generates RewriteCond !gptbot [NC] from them" '[[ "$(wpcli eval "echo \$GLOBALS[\"wp_fastest_cache\"]->excludeRules();")" == *"RewriteCond %{HTTP_USER_AGENT} !gptbot [NC]"* ]]'
wpcli option update WpFastestCacheExclude '[{"prefix":"contain","content":"mybot","type":"useragent"},{"prefix":"contain","content":"gptbot","type":"useragent"}]' --quiet
wpcli plugin deactivate norg-edge-router --quiet
check "deactivation removes only our rules" '[[ "$(wpcli option get WpFastestCacheExclude)" == *mybot* && "$(wpcli option get WpFastestCacheExclude)" != *gptbot* ]]'
wpcli plugin activate norg-edge-router --quiet; wpcli plugin deactivate wp-fastest-cache --quiet; wpcli option delete WpFastestCacheExclude

echo "LiteSpeed Cache (served by the LiteSpeed server: configuration proof)"
wpcli plugin activate litespeed-cache --quiet
wpcli norg-edge apply-cache-bypass >/dev/null
check "tokens stored in Do Not Cache User Agents" '[[ "$(wpcli eval "echo implode(\",\", apply_filters(\"litespeed_conf\", \"cache-exc_useragents\"));")" == *gptbot* ]]'
check ".htaccess carries LiteSpeed's no-cache rule for them" 'grep -q "RewriteCond %{HTTP_USER_AGENT} .*gptbot.* \[NC\]" "$WP_DIR/.htaccess"'
wpcli plugin deactivate norg-edge-router --quiet
check "deactivation removes them" '[[ "$(wpcli eval "echo implode(\",\", apply_filters(\"litespeed_conf\", \"cache-exc_useragents\"));")" != *gptbot* ]]'
wpcli plugin activate norg-edge-router --quiet; wpcli plugin deactivate litespeed-cache --quiet

printf '\n%s passed, %s failed\n' "$PASS" "$FAIL"; [ "$FAIL" -eq 0 ]
